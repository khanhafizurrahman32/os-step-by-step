#!/usr/bin/env python3
"""Collect every flashcard from the lessons into importable decks.

A flashcard is any block in a lesson written as:

    <details markdown="1"><summary>Question</summary>

    Answer

    </details>

Outputs:
  flashcards/os-step-by-step-anki.txt  Anki import file (tab-separated, HTML, tags)
  flashcards/os-step-by-step.csv       plain CSV (Quizlet, RemNote, spreadsheets)
  docs/review/os-step-by-step-anki.txt copy so the website can offer a download
  docs/review/flashcards.md            the Flashcards page, with every card listed

Run from the repository root:  python scripts/build_flashcards.py
"""
import csv
import html
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
PARTS = ["virtualization", "concurrency", "persistence", "distribution"]
CARD = re.compile(r'<details markdown="1"><summary>(.*?)</summary>\s*(.*?)\s*</details>', re.S)


def md_inline_to_html(text: str) -> str:
    text = html.escape(text.strip(), quote=False)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", text)
    return text.replace("\n", "<br>")


def lessons():
    for part in PARTS:
        for path in sorted((DOCS / part).glob("l[0-9]*.md")):
            text = path.read_text(encoding="utf-8")
            title = text.splitlines()[0].lstrip("# ").strip()
            lesson_id = title.split("·")[0].strip()          # e.g. "L09"
            cards = [(q.strip(), a.strip()) for q, a in CARD.findall(text)]
            yield part, path, title, lesson_id, cards


def main():
    out_dir = ROOT / "flashcards"
    out_dir.mkdir(exist_ok=True)
    anki = out_dir / "os-step-by-step-anki.txt"
    plain = out_dir / "os-step-by-step.csv"

    rows, sections = [], []
    for part, path, title, lesson_id, cards in lessons():
        sections.append((part, path, title, cards))
        for q, a in cards:
            rows.append((part, lesson_id, title, q, a))

    with anki.open("w", encoding="utf-8", newline="") as f:
        f.write("#separator:tab\n#html:true\n#tags column:3\n#deck:OS Step by Step\n")
        for part, lesson_id, title, q, a in rows:
            front = f"{md_inline_to_html(q)}<br><small>{html.escape(title)}</small>"
            tags = f"ostep {part} {lesson_id}"
            f.write(f"{front}\t{md_inline_to_html(a)}\t{tags}\n")

    with plain.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["question", "answer", "lesson", "part"])
        for part, lesson_id, title, q, a in rows:
            w.writerow([q, a, title, part])

    shutil.copy(anki, DOCS / "review" / anki.name)

    lines = [
        "# Flashcards (Anki)",
        "",
        f"Every flashcard from the lessons — **{len(rows)} cards** — in one deck. "
        "This page is generated by `scripts/build_flashcards.py`; edit the lessons, not this page.",
        "",
        "## Import into Anki (2 minutes)",
        "",
        f"1. Download **[os-step-by-step-anki.txt]({anki.name})** "
        "(or take it from the `flashcards/` folder of the repo).",
        "2. In Anki: **File → Import**, pick the file. The deck name, tab separator, HTML and tags "
        "are set by the file's header lines, so the defaults are right.",
        "3. Study daily. Anki's spacing replaces the +1/+3/+7/+21-day schedule in "
        "[the recall system](../start/recall-system.md).",
        "",
        "Tags let you study one part or lesson: in the browser search for `tag:concurrency` or `tag:L14`. "
        "Unsuspend only the lessons you've done, so you're never quizzed on material you haven't read.",
        "",
        "Prefer Quizlet, RemNote or a spreadsheet? Use `flashcards/os-step-by-step.csv`.",
        "",
        "## All cards",
        "",
        "Cover the right column and test yourself.",
    ]
    current_part = None
    for part, path, title, cards in sections:
        if part != current_part:
            lines += ["", f"### {part.capitalize()}"]
            current_part = part
        rel = f"../{part}/{path.name}"
        lines += ["", f"**[{title}]({rel})**", "", "| Question | Answer |", "|---|---|"]
        for q, a in cards:
            cell_q = q.replace("|", "\\|").replace("\n", " ")
            cell_a = a.replace("|", "\\|").replace("\n", " ")
            lines.append(f"| {cell_q} | {cell_a} |")
    (DOCS / "review" / "flashcards.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    build_glossary()
    print(f"{len(rows)} cards from {len(sections)} lessons -> {anki.relative_to(ROOT)}, {plain.relative_to(ROOT)}")


def build_glossary():
    """Turn includes/glossary.md (the hover-tooltip definitions) into a readable Glossary page."""
    entries = re.findall(r"^\*\[(.+?)\]: (.+)$", (ROOT / "includes" / "glossary.md").read_text(encoding="utf-8"), re.M)
    seen, rows = set(), []
    for term, meaning in sorted(entries, key=lambda e: e[0].lower()):
        key = term.lower().rstrip("s")
        if key in seen:          # skip plural duplicates such as TLB / TLBs
            continue
        seen.add(key)
        rows.append(f"| **{term}** | {meaning.replace('|', '/')} |")
    page = [
        "# Glossary",
        "",
        f"All **{len(rows)} terms** used in the lessons. On the website, every one of these terms has a dotted underline: "
        "hover over it (or tap it on a phone) to see this definition without leaving the page.",
        "",
        "To add or change a definition, edit `includes/glossary.md` and re-run `python scripts/build_flashcards.py`.",
        "",
        "| Term | Meaning |",
        "|---|---|",
        *rows,
    ]
    (DOCS / "review" / "glossary.md").write_text("\n".join(page) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
